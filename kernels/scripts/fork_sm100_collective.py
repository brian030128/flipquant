#!/usr/bin/env python3
"""Derive src/collective/sm100_blockscaled_mma_mixed.hpp from CUTLASS's vendored mainloop.

The mixed-format kernel needs to change about ten lines of a 1100-line collective. Checking in a
hand-edited copy would make those ten lines invisible the next time CUTLASS is bumped, so the copy
is generated instead: this script states each edit as an explicit, order-independent rewrite and
fails loudly if the anchor it expects has moved.

Run after a CUTLASS submodule bump; the result is checked in.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "3rdparty/cutlass/include/cutlass/gemm/collective/sm100_blockscaled_mma_warpspecialized.hpp"
DST = ROOT / "src/collective/sm100_blockscaled_mma_mixed.hpp"

POLICY = "MainloopSm100TmaUmmaWarpSpecializedBlockScaled"
MIXED_POLICY = POLICY + "Mixed"

BANNER = f"""// GENERATED by scripts/fork_sm100_collective.py from CUTLASS's
// {SRC.relative_to(ROOT)}
// Do not edit by hand -- edit the script and regenerate.
//
// The fork exists to make the UMMA *instruction descriptor's* A/B format fields settable per MMA
// rather than fixed at compile time. On sm_100 that is nearly free: tcgen05.mma takes its
// instruction descriptor in a general-purpose register (see the "r"(uint32_t(idescE>>32)) operand
// in cute/arch/mma_sm100_umma.hpp), so selecting E0M3 instead of E2M1 is a register write, not a
// different instruction. This is the whole reason the sm_120 branch problem does not reappear
// here -- on sm_120 the format is two bits of the SASS opcode, so a runtime choice meant a branch,
// and a predicated-off OMMA still burned a tensor-pipe issue slot.
//
// Everything below is CUTLASS's code except for the edits this script applies, each marked
// "MIXFP4:".

"""

EDITS = []


def edit(name, old, new, count=1):
    EDITS.append((name, old, new, count))


# 1. Resolve to our dispatch-policy tag, not CUTLASS's, so both collectives can coexist.
edit("specialization tag", f"    {POLICY}<\n", f"    {MIXED_POLICY}<\n")
edit("DispatchPolicy alias", f"  using DispatchPolicy = {POLICY}<\n",
     f"  using DispatchPolicy = {MIXED_POLICY}<\n")

# 2. Host-side arguments: the two format overrides.
edit("Arguments fields", """    RuntimeDataTypeA runtime_data_type_a{};
    RuntimeDataTypeB runtime_data_type_b{};
  };

  // Device side kernel params""", """    RuntimeDataTypeA runtime_data_type_a{};
    RuntimeDataTypeB runtime_data_type_b{};
    // MIXFP4: UMMA::MXF4Format to force into the instruction descriptor's a_format_/b_format_.
    // CUTLASS only names E2M1 (=1); 0 is the undocumented evenly-spaced INT4/E0M3 codebook.
    // kFmtKeep leaves whatever make_instr_desc_block_scaled() derived from the C++ element type.
    uint8_t fmt_a{kFmtKeep};
    uint8_t fmt_b{kFmtKeep};
  };

  // Device side kernel params""")

# 3. Device-side params.
edit("Params fields", """    RuntimeDataTypeA runtime_data_type_a;
    RuntimeDataTypeB runtime_data_type_b;
  };""", """    RuntimeDataTypeA runtime_data_type_a;
    RuntimeDataTypeB runtime_data_type_b;
    uint8_t fmt_a;  // MIXFP4
    uint8_t fmt_b;  // MIXFP4
  };""")

# 4. Carry them through to_underlying_arguments.
edit("to_underlying_arguments", """      args.runtime_data_type_a,
      args.runtime_data_type_b
    };""", """      args.runtime_data_type_a,
      args.runtime_data_type_b,
      args.fmt_a,  // MIXFP4
      args.fmt_b   // MIXFP4
    };""")

# 5. Constructor capture.
edit("ctor init list", """    , runtime_data_type_a_(params.runtime_data_type_a)
    , runtime_data_type_b_(params.runtime_data_type_b) {""", """    , runtime_data_type_a_(params.runtime_data_type_a)
    , runtime_data_type_b_(params.runtime_data_type_b)
    , fmt_a_(params.fmt_a)      // MIXFP4
    , fmt_b_(params.fmt_b) {    // MIXFP4""")

# 6. Members.
edit("member decls", """  RuntimeDataTypeA runtime_data_type_a_{};
  RuntimeDataTypeB runtime_data_type_b_{};""", """  RuntimeDataTypeA runtime_data_type_a_{};
  RuntimeDataTypeB runtime_data_type_b_{};
  uint8_t fmt_a_{kFmtKeep};  // MIXFP4
  uint8_t fmt_b_{kFmtKeep};  // MIXFP4""")

# 7. The override itself, right where CUTLASS already rewrites the descriptor for runtime dtypes.
edit("idesc override", """    if constexpr (IsRuntimeDataType) {
      // Update instruction descriptor according to runtime argument.
      // Applying bitmask (0b111) to help compiler deduce that the conversion and assignment are safe.
      tiled_mma.idesc_.a_format_ = uint8_t(runtime_data_type_a_) & 0b111;
      tiled_mma.idesc_.b_format_ = uint8_t(runtime_data_type_b_) & 0b111;
    }""", """    if constexpr (IsRuntimeDataType) {
      // Update instruction descriptor according to runtime argument.
      // Applying bitmask (0b111) to help compiler deduce that the conversion and assignment are safe.
      tiled_mma.idesc_.a_format_ = uint8_t(runtime_data_type_a_) & 0b111;
      tiled_mma.idesc_.b_format_ = uint8_t(runtime_data_type_b_) & 0b111;
    }

    // MIXFP4: the same rewrite, but reachable for the block-scaled FP4 types CUTLASS does not
    // expose a runtime dtype for. Uniform over the launch -- per-granule selection is a separate
    // step; this one exists to establish what format enum 0 actually decodes as on sm_100.
    if (fmt_a_ != kFmtKeep) { tiled_mma.idesc_.a_format_ = fmt_a_ & 0b111; }
    if (fmt_b_ != kFmtKeep) { tiled_mma.idesc_.b_format_ = fmt_b_ & 0b111; }""")


def main():
    text = SRC.read_text()

    for name, old, new, count in EDITS:
        found = text.count(old)
        if found != count:
            sys.exit(f"anchor '{name}' matched {found} times, expected {count} -- "
                     f"CUTLASS moved underneath the fork; update {__file__}")
        text = text.replace(old, new, count)

    # The sentinel and the format enum, injected just inside the namespace.
    anchor = "namespace cutlass::gemm::collective {\nusing namespace cute;\n"
    if text.count(anchor) != 1:
        sys.exit("namespace anchor not found")
    text = text.replace(anchor, anchor + """
// MIXFP4: sentinel meaning "do not override"; any real format fits in 3 bits.
static constexpr uint8_t kFmtKeep = 0xFF;
// MIXFP4: the block-scaled FP4 format enum as the hardware reads it out of the instruction
// descriptor. cute::UMMA::MXF4Format names only E2M1; enum 0 is an evenly-spaced signed INT4
// codebook (E0M3). Values 2-7 are not distinct formats.
struct MixedFmt {
  static constexpr uint8_t kE0M3 = 0;
  static constexpr uint8_t kE2M1 = 1;
};
""", 1)

    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(BANNER + text)
    print(f"wrote {DST.relative_to(ROOT)} ({len(text.splitlines())} lines, {len(EDITS)} edits)")


if __name__ == "__main__":
    main()
